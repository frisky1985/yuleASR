#!/usr/bin/env python3
"""MC/DC gate for ASIL modules (host measurement).

Consumes the aggregated report produced by ``tools/aggregate_mcdc.py`` and
checks every ASIL module listed in ``.yuleosh/ci-config.yaml`` under ``mcdc``.

Evidence rules mirror ``tools/check_coverage_gate.py``: the report must be
generated by the trusted pipeline, bind to the current commit, use repository
relative paths and contain real data.  A missing module (zero decisions) is a
failure, not a silent pass — an uninstrumented ASIL module is exactly the kind
of false negative this gate exists to prevent.

Usage:
    python3 tools/check_mcdc_gate.py [path/to/mcdc-coverage.json]
"""

import fnmatch
import json
import os
import subprocess
import sys

try:
    import yaml
except ImportError:  # pragma: no cover - CI installs pyyaml
    yaml = None

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CI_CONFIG = os.path.join(BASE_DIR, ".yuleosh", "ci-config.yaml")
MCDC_JSON = os.path.join(BASE_DIR, ".yuleosh", "reports", "mcdc-coverage.json")


def load_config():
    if yaml is None:
        print("  ❌ PyYAML is required (pip install pyyaml)")
        return {}
    with open(CI_CONFIG, encoding="utf-8") as handle:
        return (yaml.safe_load(handle) or {}).get("mcdc", {})


def is_excluded(path, patterns):
    for pattern in patterns:
        if pattern.endswith("/"):
            if path.startswith(pattern):
                return True
        elif fnmatch.fnmatch(path, pattern):
            return True
    return False


def module_of(path, scope):
    """Longest matching scope prefix, or None."""
    matches = [prefix for prefix in scope if path == prefix or path.startswith(prefix + "/")]
    return max(matches, key=len) if matches else None


def validate_evidence(report):
    failures = []
    if report.get("format") != "mcdc-v1":
        failures.append("unexpected report format — not produced by aggregate_mcdc.py")

    provenance = report.get("provenance") or {}
    if not provenance:
        failures.append("missing provenance block — report was not generated by the trusted pipeline")
    else:
        try:
            head = subprocess.check_output(
                ["git", "rev-parse", "HEAD"], cwd=BASE_DIR, text=True
            ).strip()
        except Exception:
            head = "unknown"
        if provenance.get("git_sha") != head:
            failures.append(
                f"stale evidence: git_sha={provenance.get('git_sha', '')[:8]} != HEAD={head[:8]}"
            )
        if provenance.get("measurement") != "host":
            failures.append("provenance.measurement is not 'host'")
        tool = provenance.get("tool") or {}
        if tool.get("llvm_cov") in (None, "unknown"):
            failures.append("provenance missing llvm-cov version")

    absolute = [f["file"] for f in report.get("files", []) if os.path.isabs(f.get("file", ""))]
    if absolute:
        failures.append(f"{len(absolute)} file(s) use absolute paths (e.g. {absolute[0][:80]})")

    if report.get("totals", {}).get("count", 0) == 0:
        failures.append("totals.count=0 — no MC/DC decisions were measured")

    return failures


def check(report_path):
    if yaml is None:
        print("  ❌ PyYAML is required to read mcdc config (pip install pyyaml)")
        return False
    config = load_config()
    if not config.get("enabled", False):
        print("MC/DC gate: disabled in .yuleosh/ci-config.yaml")
        return True

    with open(report_path, encoding="utf-8") as handle:
        report = json.load(handle)

    failures = validate_evidence(report)
    for failure in failures:
        print(f"  ❌ EVIDENCE FAIL: {failure}")
    if failures:
        print("  ❌ Gate BLOCKED: MC/DC evidence is not trustworthy")
        return False

    scope = config.get("scope") or []
    excludes = config.get("exclude") or []
    default_threshold = float(config.get("threshold", 100.0))
    module_thresholds = config.get("module_thresholds") or {}
    target = float(config.get("target", 100.0))
    enforce = bool(config.get("enforce", True))

    if not scope:
        print("  ❌ Gate BLOCKED: mcdc.scope is empty")
        return False

    stats = {prefix: {"count": 0, "covered": 0} for prefix in scope}
    for entry in report.get("files", []):
        path = entry.get("file", "")
        if is_excluded(path, excludes):
            continue
        module = module_of(path, scope)
        if module is None:
            continue
        mcdc = entry.get("mcdc") or {}
        stats[module]["count"] += int(mcdc.get("count", 0))
        stats[module]["covered"] += int(mcdc.get("covered", 0))

    print("MC/DC Gate Check (host, ASIL modules)")
    print(f"  Commit:   {report['provenance']['git_sha'][:8]}")
    print(f"  Tool:     {report['provenance']['tool'].get('llvm_cov', 'unknown')}")
    print(f"  Target:   {target:.1f}%  (enforce={enforce})")
    print(f"  {'Module':<34} {'Covered':>10} {'Rate':>8} {'Threshold':>10}  Status")

    passed = True
    for prefix in scope:
        count = stats[prefix]["count"]
        covered = stats[prefix]["covered"]
        threshold = float(module_thresholds.get(prefix, default_threshold))
        if count == 0:
            print(f"  {prefix:<34} {'0/0':>10} {'n/a':>8} {threshold:>9.1f}%  ❌ NO DATA")
            passed = False
            continue
        rate = 100.0 * covered / count
        ok = rate >= threshold
        passed = passed and ok
        status = "✅" if ok else "❌"
        print(
            f"  {prefix:<34} {f'{covered}/{count}':>10} "
            f"{rate:>7.1f}% {threshold:>9.1f}%  {status}"
        )

    if passed:
        print("  ✅ Gate PASSED")
    else:
        print("  ❌ Gate FAILED")
        if not enforce:
            print("     (enforce=false: reported only, CI not blocked)")
            return True
    return passed


if __name__ == "__main__":
    path = sys.argv[1] if len(sys.argv) > 1 else MCDC_JSON
    sys.exit(0 if check(path) else 1)

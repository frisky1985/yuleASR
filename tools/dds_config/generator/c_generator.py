"""
DDS Configuration C Code Generator

Generates C header and source files from DDS configuration.
Supports AUTOSAR integration and E2E protection configuration.
"""

from pathlib import Path
from typing import Dict, Any, List, Optional, Union
from datetime import datetime


class CGenerator:
    """Generator for DDS C code configuration files."""
    
    def __init__(self):
        self.output_dir: Optional[Path] = None
        self.config: Dict[str, Any] = {}
        self.indent = "    "
    
    def generate(self, config: Dict[str, Any], output_dir: Union[str, Path]) -> List[Path]:
        """
        Generate C code from configuration.
        
        Args:
            config: Configuration dictionary
            output_dir: Output directory path
            
        Returns:
            List of generated file paths
        """
        self.config = config
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        
        generated_files = []
        
        # Generate main configuration header
        dds_cfg_path = self._generate_dds_cfg_h()
        generated_files.append(dds_cfg_path)
        
        # Generate topic configuration header
        topic_cfg_path = self._generate_dds_topic_cfg_h()
        generated_files.append(topic_cfg_path)
        
        # Generate QoS configuration header
        qos_cfg_path = self._generate_dds_qos_cfg_h()
        generated_files.append(qos_cfg_path)
        
        # Generate transport configuration
        transport_cfg_path = self._generate_dds_transport_cfg_h()
        generated_files.append(transport_cfg_path)
        
        # Generate source file
        source_path = self._generate_dds_cfg_c()
        generated_files.append(source_path)
        
        # Generate AUTOSAR integration if needed
        if config.get('autosar'):
            autosar_path = self._generate_bswm_dds_rules_h()
            generated_files.append(autosar_path)
        
        return generated_files
    
    def _generate_header_guard(self, name: str) -> str:
        """Generate header guard macro."""
        return f"DDS_{name.upper()}_H"
    
    def _generate_file_header(self, filename: str, description: str) -> str:
        """Generate file header comment."""
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        return f"""/**
 * @file {filename}
 * @brief {description}
 * 
 * @warning This file is auto-generated by DDS Configuration Tool.
 *          Do not edit manually.
 * 
 * Generated: {timestamp}
 * Version: 1.0
 */

#ifndef {self._generate_header_guard(filename.replace('.', '_'))}
#define {self._generate_header_guard(filename.replace('.', '_'))}

/*==================================================================================================
*                                        INCLUDE FILES
==================================================================================================*/

"""
    
    def _generate_file_footer(self, filename: str) -> str:
        """Generate file footer."""
        return f"""
#endif /* {self._generate_header_guard(filename.replace('.', '_'))} */
/* End of file */
"""
    
    def _generate_dds_cfg_h(self) -> Path:
        """Generate Dds_Cfg.h main configuration header."""
        filename = "Dds_Cfg.h"
        filepath = self.output_dir / "include" / "dds" / filename
        filepath.parent.mkdir(parents=True, exist_ok=True)
        
        content = []
        content.append(self._generate_file_header(filename, "DDS Main Configuration"))
        
        # Includes
        content.append("#include \"Std_Types.h\"")
        content.append("#include \"Dds_Types.h\"")
        content.append("")
        
        # Version info
        content.append("/*==================================================================================================")
        content.append("*                                       VERSION INFO")
        content.append("==================================================================================================*/")
        content.append("")
        content.append("#define DDS_CFG_MAJOR_VERSION    1u")
        content.append("#define DDS_CFG_MINOR_VERSION    0u")
        content.append("#define DDS_CFG_PATCH_VERSION    0u")
        content.append("")
        
        # Domain configuration
        domain = self.config.get('domain', {})
        content.append("/*==================================================================================================")
        content.append("*                                       DOMAIN CONFIGURATION")
        content.append("==================================================================================================*/")
        content.append("")
        content.append(f"#define DDS_CFG_DOMAIN_ID        ({domain.get('domain_id', 0)}U)")
        content.append(f"#define DDS_CFG_DOMAIN_NAME      \"{domain.get('name', 'default')}\"")
        content.append("")
        
        # Discovery configuration
        discovery = domain.get('discovery', {})
        content.append("/* Discovery Settings */")
        content.append(f"#define DDS_CFG_DISCOVERY_PROTOCOL    DDS_DISC_{discovery.get('protocol', 'SIMPLE')}")
        content.append(f"#define DDS_CFG_LEASE_DURATION_SEC    ({discovery.get('lease_duration', 10)}U)")
        content.append(f"#define DDS_CFG_ANNOUNCE_PERIOD_SEC   ({discovery.get('announce_period', 5)}U)")
        content.append("")
        
        # Multicast configuration
        multicast = discovery.get('multicast', {})
        content.append("/* Multicast Settings */")
        content.append(f"#define DDS_CFG_MULTICAST_ENABLED     STD_{'ENABLED' if multicast.get('enabled', True) else 'DISABLED'}")
        content.append(f"#define DDS_CFG_MULTICAST_ADDR        \"{multicast.get('address', '239.255.0.1')}\"")
        content.append(f"#define DDS_CFG_MULTICAST_PORT        ({multicast.get('port', 7400)}U)")
        content.append("")
        
        # Transport configuration
        transport = domain.get('transport', {})
        content.append("/*==================================================================================================")
        content.append("*                                      TRANSPORT CONFIGURATION")
        content.append("==================================================================================================*/")
        content.append("")
        content.append(f"#define DDS_CFG_DEFAULT_TRANSPORT     DDS_TRANSPORT_{transport.get('default', 'UDPv4')}")
        content.append(f"#define DDS_CFG_SHM_ENABLED           STD_{'ENABLED' if transport.get('shm_enabled', True) else 'DISABLED'}")
        content.append(f"#define DDS_CFG_INTRA_PROCESS         STD_{'ENABLED' if transport.get('intra_process', True) else 'DISABLED'}")
        content.append("")
        
        # Resource limits
        resources = domain.get('resources', {})
        content.append("/*==================================================================================================")
        content.append("*                                      RESOURCE LIMITS")
        content.append("==================================================================================================*/")
        content.append("")
        content.append(f"#define DDS_CFG_MAX_PARTICIPANTS      ({resources.get('max_participants', 10)}U)")
        content.append(f"#define DDS_CFG_MAX_DOMAINS           ({resources.get('max_domains', 1)}U)")
        content.append(f"#define DDS_CFG_SHM_SIZE_KB           ({resources.get('shm_size_kb', 65536)}U)")
        content.append(f"#define DDS_CFG_SHM_SEGMENTS          ({resources.get('shm_segments', 10)}U)")
        content.append("")
        
        # Timing configuration
        timing = domain.get('timing', {})
        content.append("/*==================================================================================================")
        content.append("*                                       TIMING CONFIGURATION")
        content.append("==================================================================================================*/")
        content.append("")
        content.append(f"#define DDS_CFG_SPIN_FREQUENCY        ({timing.get('spin_frequency', 100)}U)")
        content.append(f"#define DDS_CFG_MAX_BLOCKING_MS       ({timing.get('max_blocking_time', 1000)}U)")
        content.append("")
        
        # Topic count
        topics = self.config.get('topics', [])
        content.append("/*==================================================================================================")
        content.append("*                                       TOPIC CONFIGURATION")
        content.append("==================================================================================================*/")
        content.append("")
        content.append(f"#define DDS_CFG_NUM_TOPICS            ({len(topics)}U)")
        content.append("")
        
        # Extern declarations
        content.append("/*==================================================================================================")
        content.append("*                                  EXTERNAL FUNCTION DECLARATIONS")
        content.append("==================================================================================================*/")
        content.append("")
        content.append("extern void Dds_Init(const Dds_ConfigType* configPtr);")
        content.append("extern void Dds_Deinit(void);")
        content.append("extern Std_ReturnType Dds_Start(void);")
        content.append("extern void Dds_Stop(void);")
        content.append("")
        
        content.append(self._generate_file_footer(filename))
        
        filepath.write_text('\n'.join(content))
        return filepath
    
    def _generate_dds_topic_cfg_h(self) -> Path:
        """Generate Dds_TopicCfg.h topic configuration header."""
        filename = "Dds_TopicCfg.h"
        filepath = self.output_dir / "include" / "dds" / filename
        filepath.parent.mkdir(parents=True, exist_ok=True)
        
        content = []
        content.append(self._generate_file_header(filename, "DDS Topic Configuration"))
        
        content.append("#include \"Dds_Cfg.h\"")
        content.append("#include \"Dds_Types.h\"")
        content.append("")
        
        # Topic IDs enum
        content.append("/*==================================================================================================")
        content.append("*                                       TOPIC IDENTIFIERS")
        content.append("==================================================================================================*/")
        content.append("")
        content.append("typedef enum")
        content.append("{")
        
        topics = self.config.get('topics', [])
        for i, topic in enumerate(topics):
            topic_name = topic.get('name', f'TOPIC_{i}').upper()
            content.append(f"    DDS_TOPIC_ID_{topic_name} = {i}U,")
        
        if not topics:
            content.append("    DDS_TOPIC_ID_NONE = 0U,")
        
        content.append("    DDS_TOPIC_ID_MAX")
        content.append("} Dds_TopicIdType;")
        content.append("")
        
        # Topic kinds enum
        content.append("/*==================================================================================================")
        content.append("*                                       TOPIC KINDS")
        content.append("==================================================================================================*/")
        content.append("")
        content.append("typedef enum")
        content.append("{")
        content.append("    DDS_TOPIC_KIND_STANDARD = 0U,")
        content.append("    DDS_TOPIC_KIND_SIGNAL,")
        content.append("    DDS_TOPIC_KIND_SERVICE,")
        content.append("    DDS_TOPIC_KIND_EVENT,")
        content.append("    DDS_TOPIC_KIND_FIELD")
        content.append("} Dds_TopicKindType;")
        content.append("")
        
        # Topic configuration structure
        content.append("/*==================================================================================================")
        content.append("*                                  TOPIC CONFIGURATION STRUCTURES")
        content.append("==================================================================================================*/")
        content.append("")
        content.append("typedef struct")
        content.append("{")
        content.append(f"{self.indent}Dds_TopicIdType       topicId;")
        content.append(f"{self.indent}Dds_TopicKindType     kind;")
        content.append(f"{self.indent}const char*           name;")
        content.append(f"{self.indent}const char*           dataType;")
        content.append(f"{self.indent}uint16                maxInstances;")
        content.append(f"{self.indent}boolean               e2eEnabled;")
        content.append(f"{self.indent}uint8                 e2eProfile;")
        content.append(f"{self.indent}uint16                e2eDataId;")
        content.append("} Dds_TopicConfigType;")
        content.append("")
        
        # Topic configuration declarations
        content.append("/*==================================================================================================")
        content.append("*                                  TOPIC CONFIGURATION DATA")
        content.append("==================================================================================================*/")
        content.append("")
        content.append(f"#define DDS_CFG_NUM_TOPIC_CONFIGS     ({len(topics)}U)")
        content.append("")
        content.append("extern const Dds_TopicConfigType Dds_TopicConfigs[DDS_CFG_NUM_TOPIC_CONFIGS];")
        content.append("")
        
        # E2E profile definitions
        content.append("/*==================================================================================================")
        content.append("*                                       E2E PROFILES")
        content.append("==================================================================================================*/")
        content.append("")
        content.append("#define DDS_E2E_PROFILE_NONE          0x00U")
        content.append("#define DDS_E2E_PROFILE_P01           0x01U")
        content.append("#define DDS_E2E_PROFILE_P02           0x02U")
        content.append("#define DDS_E2E_PROFILE_P04           0x04U")
        content.append("#define DDS_E2E_PROFILE_P05           0x05U")
        content.append("#define DDS_E2E_PROFILE_P06           0x06U")
        content.append("#define DDS_E2E_PROFILE_P07           0x07U")
        content.append("#define DDS_E2E_PROFILE_P11           0x0BU")
        content.append("#define DDS_E2E_PROFILE_P22           0x16U")
        content.append("")
        
        content.append(self._generate_file_footer(filename))
        
        filepath.write_text('\n'.join(content))
        return filepath
    

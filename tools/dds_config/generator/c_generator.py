    def _generate_dds_cfg_c(self) -> Path:
        """Generate Dds_Cfg.c source file."""
        filename = "Dds_Cfg.c"
        filepath = self.output_dir / "src" / "dds" / filename
        filepath.parent.mkdir(parents=True, exist_ok=True)
        
        content = []
        content.append(self._generate_file_header(filename, "DDS Configuration Source"))
        
        content.append("#include \"Dds_Cfg.h\"")
        content.append("#include \"Dds_TopicCfg.h\"")
        content.append("#include \"Dds_QosCfg.h\"")
        content.append("#include \"Dds_TransportCfg.h\"")
        content.append("")
        
        # Topic configurations
        topics = self.config.get('topics', [])
        content.append("/*==================================================================================================")
        content.append("*                                  TOPIC CONFIGURATION DATA")
        content.append("==================================================================================================*/")
        content.append("")
        content.append("const Dds_TopicConfigType Dds_TopicConfigs[DDS_CFG_NUM_TOPIC_CONFIGS] =")
        content.append("{")
        
        for i, topic in enumerate(topics):
            topic_name = topic.get('name', f'topic_{i}')
            kind = topic.get('kind', 'STANDARD')
            data_type = topic.get('data_type', 'void')
            max_instances = topic.get('max_instances', 1)
            security = topic.get('security', {})
            e2e_enabled = 'TRUE' if security.get('e2e_enabled', False) else 'FALSE'
            e2e_profile = security.get('e2e_profile', 'P01')
            e2e_data_id = security.get('e2e_data_id', 0)
            
            content.append(f"    {{ /* {topic_name} */")
            content.append(f"        .topicId = DDS_TOPIC_ID_{topic_name.upper()},")
            content.append(f"        .kind = DDS_TOPIC_KIND_{kind},")
            content.append(f"        .name = \"{topic_name}\",")
            content.append(f"        .dataType = \"{data_type}\",")
            content.append(f"        .maxInstances = {max_instances}U,")
            content.append(f"        .e2eEnabled = {e2e_enabled},")
            content.append(f"        .e2eProfile = DDS_E2E_PROFILE_{e2e_profile},")
            content.append(f"        .e2eDataId = {e2e_data_id}U")
            content.append("    },")
        
        content.append("};")
        content.append("")
        
        # QoS profiles
        profiles = self.config.get('qos_profiles', [])
        if profiles:
            content.append("/*==================================================================================================")
            content.append("*                                  QOS PROFILE DATA")
            content.append("==================================================================================================*/")
            content.append("")
            
            for profile in profiles:
                profile_name = profile.get('name', 'default')
                reliability = profile.get('reliability', {})
                durability = profile.get('durability', {})
                history = profile.get('history', {})
                liveliness = profile.get('liveliness', {})
                
                rel_kind = reliability.get('kind', 'RELIABLE')
                max_blocking = reliability.get('max_blocking_time', 100)
                dur_kind = durability.get('kind', 'VOLATILE')
                hist_kind = history.get('kind', 'KEEP_LAST')
                hist_depth = history.get('depth', 1)
                live_kind = liveliness.get('kind', 'AUTOMATIC')
                lease_dur = liveliness.get('lease_duration', 10)
                deadline = profile.get('deadline', {}).get('period', 0) * 1000
                latency = profile.get('latency_budget', 0) * 1000
                priority = profile.get('transport_priority', 0)
                
                content.append(f"const Dds_QosProfileType Dds_QosProfile_{profile_name.upper()} =")
                content.append("{")
                content.append(f"    .reliability = {{")
                content.append(f"        .kind = DDS_RELIABILITY_{rel_kind},")
                content.append(f"        .maxBlockingTimeMs = {int(max_blocking * 1000)}U")
                content.append("    },")
                content.append(f"    .durability = {{")
                content.append(f"        .kind = DDS_DURABILITY_{dur_kind}")
                content.append("    },")
                content.append(f"    .history = {{")
                content.append(f"        .kind = DDS_HISTORY_{hist_kind},")
                content.append(f"        .depth = {hist_depth}U")
                content.append("    },")
                content.append(f"    .liveliness = {{")
                content.append(f"        .kind = DDS_LIVELINESS_{live_kind},")
                content.append(f"        .leaseDurationSec = {int(lease_dur)}U")
                content.append("    },")
                content.append(f"    .deadlineMs = {int(deadline)}U,")
                content.append(f"    .latencyBudgetMs = {int(latency)}U,")
                content.append(f"    .transportPriority = {priority}U")
                content.append("};")
                content.append("")
        
        # Transport configurations
        transports = self.config.get('transports', [])
        content.append("/*==================================================================================================")
        content.append("*                                  TRANSPORT CONFIGURATION DATA")
        content.append("==================================================================================================*/")
        content.append("")
        content.append("const Dds_TransportConfigType Dds_TransportConfigs[DDS_CFG_NUM_TRANSPORTS] =")

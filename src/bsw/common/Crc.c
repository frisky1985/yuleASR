/**
 * @brief Calculates 8-bit CRC (SAE J1850 polynomial 0x1D)
 * @param Crc_DataPtr Pointer to data buffer
 * @param Crc_Length Length of data in bytes
 * @param Crc_StartValue8 Initial CRC value
 * @param Crc_IsFirstCall TRUE if first call in a sequence
 * @return Calculated 8-bit CRC
 */
uint8 Crc_CalculateCRC8(const uint8* Crc_DataPtr, uint32 Crc_Length, uint8 Crc_StartValue8, boolean Crc_IsFirstCall)
{
    uint8 crc;
    uint32 i;
    
    if (Crc_DataPtr == NULL_PTR) {
        return 0U;
    }
    
    crc = Crc_IsFirstCall ? 0xFFU : Crc_StartValue8;
    
    for (i = 0U; i < Crc_Length; i++) {
        crc = Crc8_Table[crc ^ Crc_DataPtr[i]];
    }
    
    return crc ^ 0xFFU;
}

